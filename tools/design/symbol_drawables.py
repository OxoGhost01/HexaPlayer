"""
Turns icons of the bundled Material Symbols Rounded font into white vector drawables,
for the places that can't use the font: Android Auto tabs, rows and buttons.

Icons are taken filled (FILL=1), on the font's 960 unit grid.

Usage (needs fonttools):
  python symbol_drawables.py <res/font/material_symbols_rounded.ttf> <Symbols.kt> <res/drawable> name=Symbol ...
  e.g. ic_auto_home=Home ic_auto_album=Album
"""
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

GRID = 960

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/design/symbol_drawables.py from Material Symbols Rounded ({symbol}) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{grid}"
    android:viewportHeight="{grid}">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="{path}" />
</vector>
"""


def code_points(symbols_kt: str) -> dict:
    text = open(symbols_kt, encoding="utf-8").read()
    return {name: int(cp, 16) for name, cp in re.findall(r'const val (\w+) = "\\u([0-9A-F]{4})"', text)}


def main() -> None:
    font_path, symbols_kt, out_dir, *pairs = sys.argv[1:]
    font = instancer.instantiateVariableFont(TTFont(font_path), {"FILL": 1})
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    points = code_points(symbols_kt)
    for pair in pairs:
        file_name, symbol = pair.split("=")
        pen = SVGPathPen(glyphs)
        # Font space is y up; drawables are y down.
        glyphs[cmap[points[symbol]]].draw(TransformPen(pen, (1, 0, 0, -1, 0, GRID)))
        with open(f"{out_dir}/{file_name}.xml", "w", encoding="utf-8") as out:
            out.write(TEMPLATE.format(symbol=symbol, grid=GRID, path=pen.getCommands()))
        print(file_name, symbol)


if __name__ == "__main__":
    main()
