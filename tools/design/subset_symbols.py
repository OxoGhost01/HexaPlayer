"""
Builds the bundled Material Symbols Rounded font and its Kotlin code points.

The full variable font is about 15 MB. This keeps only the icons listed in
symbols.txt, pins wght=400, GRAD=0, opsz=24 and keeps the FILL axis so icons
can switch between outlined and filled at runtime.

Usage (needs fonttools):
  python subset_symbols.py <MaterialSymbolsRounded[...].ttf> <...codepoints> symbols.txt <res/font/out.ttf> <Symbols.kt>
"""
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer


def camel(name: str) -> str:
    parts = name.split("_")
    out = "".join(p[:1].upper() + p[1:] for p in parts)
    return out if not out[0].isdigit() else "N" + out


def kotlin_string(cp: int) -> str:
    if cp <= 0xFFFF:
        return "\\u%04X" % cp
    v = cp - 0x10000
    return "\\u%04X\\u%04X" % (0xD800 + (v >> 10), 0xDC00 + (v & 0x3FF))


def main(font_path, codepoints_path, names_path, out_font, out_kt):
    codepoints = {}
    for line in open(codepoints_path):
        if line.strip():
            name, cp = line.split()
            codepoints[name] = int(cp, 16)
    names = [l.strip() for l in open(names_path) if l.strip() and not l.startswith("#")]
    missing = [n for n in names if n not in codepoints]
    if missing:
        sys.exit(f"unknown icons: {missing}")

    font = TTFont(font_path, lazy=False)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=[codepoints[n] for n in names])
    sub.subset(font)
    font = instancer.instantiateVariableFont(font, {"wght": 400, "GRAD": 0, "opsz": 24})
    font.save(out_font)

    lines = [
        "package com.oxoghost.hexaplayer.ui.common",
        "",
        "// Generated by tools/design/subset_symbols.py from tools/design/symbols.txt. Do not edit.",
        "object Symbols {",
    ]
    for n in sorted(names):
        lines.append(f'    const val {camel(n)} = "{kotlin_string(codepoints[n])}"')
    lines.append("}")
    open(out_kt, "w").write("\n".join(lines) + "\n")
    print(f"{len(names)} icons -> {out_font}")


if __name__ == "__main__":
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    main(*sys.argv[1:])
