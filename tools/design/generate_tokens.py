"""
Turns the design tokens (tokens.json from the 2.0 UI handoff) into Kotlin constants.

Usage:
  python generate_tokens.py <tokens.json> <app/src/main/java/.../ui/tokens/DesignTokens.kt>

Types (TerminalPaletteTokens, MaterialSchemeTokens, TypeToken, CoverShape...) live in
TokenTypes.kt next to the output; this script only writes values.
"""
import json
import sys

PKG = "com.oxoghost.hexaplayer.ui.tokens"


def color(hex_value: str) -> str:
    return "Color(0xFF%s)" % hex_value.lstrip("#").upper()


def number(v) -> str:
    return str(v) if isinstance(v, int) else "%sf" % v


def type_token(t: dict) -> str:
    args = [str(t["size"]), str(t["line"]), str(t["weight"])]
    if "tracking" in t:
        args.append("%sf" % float(t["tracking"]))
    return "TypeToken(%s)" % ", ".join(args)


def int_object(name: str, values: dict, indent: str) -> list:
    out = [f"{indent}object {name} {{"]
    for k, v in values.items():
        if isinstance(v, str) and v.endswith("%"):
            out.append(f"{indent}    const val {k}Percent = {int(v[:-1])}")
        else:
            out.append(f"{indent}    const val {k} = {number(v)}")
    out.append(f"{indent}}}")
    return out


def cover_art(art: dict, indent: str) -> list:
    out = [f"{indent}CoverArtTokens(", f"{indent}    background = {color(art['bg'])},", f"{indent}    shapes = listOf("]
    for s in art["shapes"]:
        if s[0] == "o":
            out.append(f"{indent}        CoverShape.Circle({s[1]}f, {s[2]}f, {s[3]}f, {color(s[4])}),")
        else:
            out.append(f"{indent}        CoverShape.Rect({s[1]}f, {s[2]}f, {s[3]}f, {s[4]}f, {color(s[5])}),")
    out += [f"{indent}    ),", f"{indent})"]
    return out


def main(src: str, dst: str):
    t = json.load(open(src, encoding="utf-8"))
    term, mat, cover = t["terminal"], t["material"], t["cover_placeholder"]
    L = [
        f"package {PKG}",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "// Generated by tools/design/generate_tokens.py from the 2.0 UI tokens.json. Do not edit.",
        "object DesignTokens {",
        "",
        "    object Terminal {",
        f'        const val DEFAULT_PALETTE = "{term["default_palette"]}"',
        f"        const val BORDER_DP = {term['border_dp']}",
        "",
        "        val palettes: Map<String, TerminalPaletteTokens> = linkedMapOf(",
    ]
    for name, p in term["palettes"].items():
        L.append(f'            "{name}" to TerminalPaletteTokens(')
        L += [f"                {role} = {color(v)}," for role, v in p.items()]
        L.append("            ),")
    L += ["        )", "", "        object Type {"]
    L += [f"            val {k} = {type_token(v)}" for k, v in term["type"].items()]
    L += ["        }", ""]
    L += int_object("Metrics", term["metrics_dp"], "        ")
    L += [""]
    L += int_object("Shape", term["shape_dp"], "        ")
    L += ["    }", "", "    object Material {", f'        const val DEFAULT_SCHEME = "{mat["default_scheme"]}"', ""]
    L.append("        val seeds: Map<String, Color> = linkedMapOf(")
    L += [f'            "{k}" to {color(v)},' for k, v in mat["seeds"].items()]
    L += ["        )", "", "        val schemes: Map<String, MaterialSchemeTokens> = linkedMapOf("]
    for name, s in mat["schemes"].items():
        L.append(f'            "{name}" to MaterialSchemeTokens(')
        L += [f"                {role} = {color(v)}," for role, v in s.items()]
        L.append("            ),")
    L += ["        )", "", "        object Type {"]
    L += [f"            val {k} = {type_token(v)}" for k, v in mat["type"].items()]
    L += ["        }", ""]
    L += int_object("Metrics", mat["metrics_dp"], "        ")
    L += [""]
    L += int_object("Shape", mat["shape_dp"], "        ")
    L += ["    }", "", "    object Cover {", "        val arts: List<CoverArtTokens> = listOf("]
    for art in cover["arts"]:
        L += [line + ("," if line.endswith(")") and line.startswith("            )") else "")
              for line in cover_art(art, "            ")]
    L += ["        )", "", "        val unknownFile: CoverArtTokens ="]
    L += cover_art(cover["unknownFile"], "            ")
    L += ["    }", "}", ""]
    open(dst, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
